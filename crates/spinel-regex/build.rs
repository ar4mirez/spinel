//! Turn the measured POSIX-bracket table into Rust.
//!
//! Six of Onigmo's fourteen brackets are unions of Unicode general categories
//! that `char`'s own predicates do not expose: `Nd` alone, `Alphabetic + Nd`,
//! `P*`, "assigned minus `C*`". `#180` had three ways to close them — embed the
//! measured ranges, take a Unicode-tables dependency, or generate Rust from the
//! oracle — and this is the third.
//!
//! A dependency was the one rejected on purpose. Its Unicode version has to be
//! kept in step with the one CRuby was built against, and a mismatch shows up as
//! exactly the kind of quiet per-codepoint disagreement `#178`'s audit was
//! written to catch. Generating from `tests/posix.txt` keeps a *measurement* as
//! the source of truth: that file is regenerated from a live CRuby by
//! `scripts/regexp-oracle.rb --generate` and re-checked against one by CI.
//!
//! Ranges rather than a bitset: 2,353 of them across the six, sorted, so a
//! lookup is a binary search over ~19 KB of `.rodata` and costs nothing at boot
//! — which matters, because every `spinel` process boots a heap.
//!
//! `tests/properties.txt`, the `\p{}` properties, is turned into Rust the same
//! way and for the same reason: every set there was measured from CRuby.

use std::fmt::Write as _;
use std::path::PathBuf;

/// The brackets that need a table. The other eight are exact on `char`'s own
/// predicates and stay there — cheaper than a binary search, and already
/// measured as agreeing on every codepoint.
const GENERATED: &[&str] = &["digit", "alnum", "print", "graph", "word", "punct"];

fn main() {
    let manifest = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").expect("cargo sets this"));
    let table = manifest.join("tests/posix.txt");
    println!("cargo:rerun-if-changed={}", table.display());
    println!("cargo:rerun-if-changed=build.rs");

    let source = std::fs::read_to_string(&table)
        .unwrap_or_else(|e| panic!("cannot read {}: {e}", table.display()));

    let mut out = String::from(
        "// Generated by build.rs from tests/posix.txt. Do not edit.\n\
         //\n\
         // One sorted, non-overlapping range list per bracket, as inclusive\n\
         // `(low, high)` pairs of scalar values.\n",
    );
    let mut written = 0;
    for line in source.lines() {
        let line = line.trim_end();
        if line.starts_with('#') || line.is_empty() {
            continue;
        }
        let Some((name, fields)) = line.split_once('\t') else {
            continue;
        };
        if !GENERATED.contains(&name) {
            continue;
        }
        let ranges = ranges(name, fields);
        let _ = writeln!(
            out,
            "static {}: &[(u32, u32)] = &[",
            name.to_uppercase().as_str()
        );
        for (low, high) in &ranges {
            let _ = writeln!(out, "    (0x{low:X}, 0x{high:X}),");
        }
        out.push_str("];\n");
        written += 1;
    }
    assert_eq!(
        written,
        GENERATED.len(),
        "tests/posix.txt is missing a bracket the engine generates a table for"
    );

    let dest =
        PathBuf::from(std::env::var("OUT_DIR").expect("cargo sets this")).join("posix_tables.rs");
    std::fs::write(&dest, out).unwrap_or_else(|e| panic!("cannot write {}: {e}", dest.display()));

    properties(&manifest);
}

/// `tests/properties.txt` as three tables: `SETS`, every property set in the
/// file's order; `NAMES`, each name and the set it reads, sorted by name for
/// a binary search; and `AGES`, each `age=` line's name and the codepoints
/// that version added, oldest first.
fn properties(manifest: &std::path::Path) {
    let table = manifest.join("tests/properties.txt");
    println!("cargo:rerun-if-changed={}", table.display());
    let source = std::fs::read_to_string(&table)
        .unwrap_or_else(|e| panic!("cannot read {}: {e}", table.display()));

    let mut out =
        String::from("// Generated by build.rs from tests/properties.txt. Do not edit.\n");
    let mut sets = String::from("static SETS: &[&[(u32, u32)]] = &[\n");
    let mut ages = String::from("static AGES: &[(&str, &[(u32, u32)])] = &[\n");
    let mut names: Vec<(String, usize)> = Vec::new();
    let mut count = 0;
    for line in source.lines() {
        if line.starts_with('#') || line.trim().is_empty() {
            continue;
        }
        let (labels, fields) = line
            .split_once('\t')
            .unwrap_or_else(|| panic!("properties.txt: no tab in {line:?}"));
        let ranges = ranges(labels, fields);
        let mut body = String::from("&[");
        for (low, high) in &ranges {
            let _ = write!(body, "(0x{low:X}, 0x{high:X}),");
        }
        body.push(']');
        if labels.starts_with("age=") {
            let _ = writeln!(ages, "    ({labels:?}, {body}),");
            continue;
        }
        let _ = writeln!(sets, "    {body},");
        names.extend(labels.split(',').map(|name| (name.to_owned(), count)));
        count += 1;
    }
    names.sort();
    assert!(
        names.windows(2).all(|w| w[0].0 < w[1].0),
        "properties.txt names a property twice"
    );
    out.push_str(&sets);
    out.push_str("];\n");
    out.push_str(&ages);
    out.push_str("];\n");
    out.push_str("static NAMES: &[(&str, u16)] = &[\n");
    for (name, index) in &names {
        let _ = writeln!(out, "    ({name:?}, {index}),");
    }
    out.push_str("];\n");

    let dest = PathBuf::from(std::env::var("OUT_DIR").expect("cargo sets this"))
        .join("property_tables.rs");
    std::fs::write(&dest, out).unwrap_or_else(|e| panic!("cannot write {}: {e}", dest.display()));
}

/// One line's `;`-separated `LO-HI` or `LO` fields, checked sorted and
/// disjoint, since the lookup is a binary search.
fn ranges(name: &str, fields: &str) -> Vec<(u32, u32)> {
    let parse = |s: &str| {
        u32::from_str_radix(s, 16).unwrap_or_else(|e| panic!("{name}: bad codepoint {s:?}: {e}"))
    };
    let ranges: Vec<(u32, u32)> = fields
        .split(';')
        .filter(|f| !f.is_empty())
        .map(|field| match field.split_once('-') {
            Some((low, high)) => (parse(low), parse(high)),
            None => (parse(field), parse(field)),
        })
        .collect();
    assert!(
        ranges.windows(2).all(|w| w[0].1 < w[1].0),
        "{name}: ranges are not sorted and disjoint"
    );
    ranges
}
