#!/usr/bin/env bash
#
# Vendor upstream pg's Ruby half into this gem:
#
#   gems/pg-spinel/vendor.sh           re-vendor, overwriting upstream's files
#   gems/pg-spinel/vendor.sh --check   fail if lib/ differs from upstream
#
# `lib/pg.rb` and `lib/pg/**/*.rb` are the pg gem's own, verbatim, from the
# packaged gem at the release this gem stands in for (its `ruby` build,
# checked against the SHA-256 rubygems.org lists), and `LICENSE-pg` and
# `BSDL-pg` are its LICENSE and BSDL. `lib/pg_ext/errorcodes.rb` is
# generated here from that gem's `ext/errorcodes.def`, the SQLSTATE classes
# upstream's C defines, as data. What else is not upstream's is
# `lib/pg_ext.rb` and the rest of `lib/pg_ext/`, Spinel's C half, which
# upstream's `lib/pg.rb` requires where CRuby loads `pg_ext.so`; nothing of
# upstream's is patched.

set -euo pipefail

here="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
version="1.7.0"
sha256="f7b536501284e883d4c9ef86dbde0313063e4aaafc23575b0017b0d572a26afb"
generated="lib/pg_ext/errorcodes.rb"

tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT
curl -sSfL -o "$tmp/pg.gem" "https://rubygems.org/gems/pg-$version.gem"
if [[ "$( (sha256sum "$tmp/pg.gem" 2>/dev/null || shasum -a 256 "$tmp/pg.gem") | cut -d' ' -f1)" != "$sha256" ]]; then
  echo "vendor.sh: pg-$version.gem is not the gem its checksum names" >&2
  exit 1
fi
mkdir -p "$tmp/gem" "$tmp/data"
tar -xf "$tmp/pg.gem" -C "$tmp/gem"
tar -xzf "$tmp/gem/data.tar.gz" -C "$tmp/data" lib LICENSE BSDL ext/errorcodes.def

# errorcodes.def's blocks, `define_error_class( "Name", "base" or NULL )`
# then its `register_error_class( "code", klass )` lines, as one entry each.
{
  echo "# frozen_string_literal: true"
  echo
  echo "# Generated by gems/pg-spinel/vendor.sh from pg $version's ext/errorcodes.def:"
  echo "# each SQLSTATE error class upstream's C defines, the code of the class it"
  echo "# derives from (nil for PG::ServerError), and the codes it is registered"
  echo "# under, in upstream's order. Do not edit."
  echo
  echo "module PG"
  echo "  module Spinel"
  echo "    ERROR_CODES = ["
  name=""
  while read -r kind a b; do
    case "$kind" in
      C)
        [[ -n "$name" ]] && echo "      [\"$name\", $base, %w[${codes# }]],"
        name="$a"
        if [[ "$b" == "-" ]]; then base="nil"; else base="\"$b\""; fi
        codes=""
        ;;
      R) codes="$codes $a" ;;
    esac
  done < <(sed -n -E \
    -e 's/.*define_error_class\( "([^"]+)", NULL \);.*/C \1 -/p' \
    -e 's/.*define_error_class\( "([^"]+)", "([^"]+)" \);.*/C \1 \2/p' \
    -e 's/.*register_error_class\( "([^"]+)", klass \);.*/R \1/p' \
    "$tmp/data/ext/errorcodes.def")
  [[ -n "$name" ]] && echo "      [\"$name\", $base, %w[${codes# }]]"
  echo "    ].freeze"
  echo "  end"
  echo "end"
} > "$tmp/errorcodes.rb"

if [[ "${1:-}" == "--check" ]]; then
  status=0
  upstream="$(cd "$tmp/data" && find lib -name '*.rb' | sort)"
  vendored="$(cd "$here" && find lib -name '*.rb' ! -path lib/pg_ext.rb ! -path 'lib/pg_ext/*' | sort)"
  if [[ "$upstream" != "$vendored" ]]; then
    echo "vendor.sh: lib/ has other files than upstream pg $version's:" >&2
    diff <(echo "$upstream") <(echo "$vendored") >&2 || true
    status=1
  fi
  while read -r file; do
    if ! cmp -s "$tmp/data/$file" "$here/$file"; then
      echo "vendor.sh: $file differs from upstream pg $version's" >&2
      status=1
    fi
  done <<<"$upstream"
  if ! cmp -s "$tmp/data/LICENSE" "$here/LICENSE-pg"; then
    echo "vendor.sh: LICENSE-pg differs from upstream pg $version's LICENSE" >&2
    status=1
  fi
  if ! cmp -s "$tmp/data/BSDL" "$here/BSDL-pg"; then
    echo "vendor.sh: BSDL-pg differs from upstream pg $version's BSDL" >&2
    status=1
  fi
  if ! cmp -s "$tmp/errorcodes.rb" "$here/$generated"; then
    echo "vendor.sh: $generated is not what upstream pg $version's ext/errorcodes.def generates" >&2
    status=1
  fi
  [[ $status -eq 0 ]] && echo "gems/pg-spinel/lib is upstream pg $version's"
  exit $status
fi

cp -R "$tmp/data/lib/." "$here/lib/"
cp "$tmp/data/LICENSE" "$here/LICENSE-pg"
cp "$tmp/data/BSDL" "$here/BSDL-pg"
mkdir -p "$here/lib/pg_ext"
cp "$tmp/errorcodes.rb" "$here/$generated"
echo "vendored upstream pg $version's lib/ into gems/pg-spinel"
