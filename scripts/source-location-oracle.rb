#!/usr/bin/env ruby
# frozen_string_literal: true

# The oracle behind `core/ruby_written.rb` (#380).
#
# Every core method in Spinel is Ruby, so every one has a location. CRuby has
# one only for the methods it writes in Ruby itself, in its `<internal:…>`
# files: `Kernel#tap` answers `["<internal:kernel>", 89]`, and `Array#<<`,
# written in C, answers `nil`. Which methods are which is not something to read
# out of CRuby's sources and retype: it is measured here, from a real Ruby
# started with no gems and nothing required, and CI re-checks it.
#
#   ruby scripts/source-location-oracle.rb --check      # CI: agree, or fail
#   ruby scripts/source-location-oracle.rb --generate   # rewrite the table
#
# Each entry is `Owner#name` for an instance method and `Owner.name` for a
# singleton one, for every module a constant names, aliases included under
# their own name. `RubyVM` is left out: it is CRuby's own machinery, and which
# of it exists depends on how that Ruby was built (YJIT or not).

TABLE = File.expand_path("../core/ruby_written.rb", __dir__)

MEASURE = <<~'RUBY'
  rows = []
  ObjectSpace.each_object(Module) do |mod|
    name = (mod.name rescue nil) or next
    next unless (Object.const_get(name).equal?(mod) rescue false)
    next if name == "RubyVM" || name.start_with?("RubyVM::")
    [[mod, "#"], [mod.singleton_class, "."]].each do |m, sep|
      names = m.instance_methods(false) + m.private_instance_methods(false) +
        m.protected_instance_methods(false)
      names.each do |meth|
        file, = m.instance_method(meth).source_location
        rows << "#{name}#{sep}#{meth}" if file&.start_with?("<internal:")
      end
    end
  end
  puts rows.uniq.sort
RUBY

HEADER = <<~TEXT
  # CRuby's core methods written in Ruby, measured. Do not edit by hand.
  #
  # Generated by `scripts/source-location-oracle.rb --generate`; CI re-runs it
  # with `--check`. `Owner#name` is an instance method and `Owner.name` a
  # singleton one: the methods CRuby defines in its `<internal:…>` files, and so
  # the only core methods whose `source_location` is not nil (#380).
TEXT

def measure
  IO.popen([RbConfig.ruby, "--disable-gems", "-e", MEASURE], &:read).split("\n")
end

def render
  rows = measure
  body = rows.map { |row| "    #{row}\n" }.join
  <<~RUBY
    #{HEADER.chomp}

    class Method
      RUBY_WRITTEN = %w[
    #{body.chomp}
      ].to_h { |entry| [entry, true] }.freeze
      private_constant :RUBY_WRITTEN
    end
  RUBY
end

case ARGV[0] || "--check"
when "--generate"
  File.write(TABLE, render)
  puts "wrote #{measure.length} methods to #{TABLE.sub("#{Dir.pwd}/", "")}"
when "--check"
  if File.read(TABLE) == render
    puts "#{TABLE}: agrees with ruby #{RUBY_VERSION}"
  else
    abort "#{TABLE} disagrees with ruby #{RUBY_VERSION}: regenerate with scripts/source-location-oracle.rb --generate"
  end
else
  abort "usage: #{$0} [--check|--generate]"
end
